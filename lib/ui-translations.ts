export function translateUiText(value: string): string {
  if (!/[\u3400-\u9fff]/u.test(value)) return value;
  const leading = value.match(/^\s*/u)?.[0] || "";
  const trailing = value.match(/\s*$/u)?.[0] || "";
  const text = value.slice(leading.length, value.length - trailing.length);
  const exact = exactTranslations[text];
  if (exact !== undefined) return `${leading}${exact}${trailing}`;
  let translated = text;
  for (const [source, target] of phraseTranslations) translated = translated.replaceAll(source, target);
  return `${leading}${translated}${trailing}`;
}

export function hasUntranslatedUiText(value: string): boolean {
  return /[\u3400-\u9fff]/u.test(translateUiText(value));
}
