import { withUiDatabase as fixture } from './database-fixture.mjs';
import { expect, test } from "@playwright/test";
test.afterEach(() => fixture(db => db.exec("DELETE FROM CollectionPlan WHERE title LIKE 'Scout UI%'")));
test("external search stays independent and does not save keywords, wishes or card links", async ({ page, context }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.goto("/collection", { waitUntil: "networkidle" });
  await expect(page.getByRole("tab")).toHaveCount(0);
  await expect(page.locator('.scout-page > .panel h2')).toHaveText(['心愿单', '跨站查询']);
  await expect(page.getByRole("heading", { name: "跨站查询", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "心愿单", exact: true })).toBeVisible();
  const before = fixture(db => ({ wishes: db.prepare("SELECT count(*) n FROM CollectionPlan").get().n, cards: db.prepare("SELECT count(*) n FROM Card").get().n }));
  await page.getByLabel("关键词", { exact: true }).fill("Scout UI 金签 & Gold");
  await expect(page.getByRole("link", { name: "eBay · 打开查询", exact: true })).toHaveAttribute("href", /_nkw=Scout\+UI\+/);
  await expect(page.locator(".scout-links > a")).toHaveCount(3);
  for (const link of await page.locator(".scout-links > a").all()) await expect(link).toHaveAttribute("rel", "noopener noreferrer");
  await page.getByRole("button", { name: "复制关键词", exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe("Scout UI 金签 & Gold");
  await expect(page.getByRole("button", { name: "保存关键词", exact: true })).toHaveCount(0);
  expect(fixture(db => ({ wishes: db.prepare("SELECT count(*) n FROM CollectionPlan").get().n, cards: db.prepare("SELECT count(*) n FROM Card").get().n }))).toEqual(before);
  expect(fixture(db => db.prepare("SELECT count(*) n FROM ScoutWatch").get().n)).toBe(0);
});
test("simple wishes retain drafts, reject invalid budgets and support edit, search and delete without acquisition", async ({ page }, testInfo) => {
  await page.goto("/collection", { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "新增心愿", exact: true }).click();
  await page.getByLabel("心愿名称 *", { exact: true }).fill("Scout UI 金签");
  await page.getByLabel("卡片主体（可选）", { exact: true }).fill("Jordan Lee");
  await page.getByLabel("预算（可选）", { exact: true }).fill("0");
  await page.getByLabel("备注（可选）", { exact: true }).fill("Long notes\n第二行");
  await page.screenshot({ path: testInfo.outputPath("simple-wish-editor.png"), fullPage: true });
  await page.reload({ waitUntil: "networkidle" });
  await expect(page.getByLabel("心愿名称 *", { exact: true })).toHaveValue("Scout UI 金签");
  await page.getByLabel("预算（可选）", { exact: true }).fill("1.234");
  await page.getByRole("button", { name: "添加心愿", exact: true }).click();
  await expect(page.locator('.scout-page').getByRole("alert")).toHaveText("金额需为非负数，最多两位小数。");
  await expect(page.getByLabel("心愿名称 *", { exact: true })).toHaveValue("Scout UI 金签");
  await page.getByLabel("预算（可选）", { exact: true }).fill("0");
  await page.getByRole("button", { name: "添加心愿", exact: true }).click();
  const wish = page.locator(".scout-wish").filter({ hasText: "Scout UI 金签" });
  await expect(wish).toContainText("CNY 0.00");
  await page.screenshot({ path: testInfo.outputPath("simple-wishlist.png"), fullPage: true });
  await expect(page.locator(".wish-editor")).toHaveCount(0);
  await expect(wish.getByRole("button")).toHaveText(["编辑", "删除"]);
  await wish.getByRole("button", { name: "编辑", exact: true }).click();
  await page.getByLabel("预算（可选）", { exact: true }).fill("123.45");
  await page.getByRole("button", { name: "保存心愿", exact: true }).click();
  await expect(wish).toContainText("CNY 123.45");
  await page.getByLabel("搜索心愿", { exact: true }).fill("Lee 第二行");
  await expect(wish).toBeVisible();
  fixture(db => {
    expect(db.prepare("SELECT count(*) n FROM ScoutWishCard").get().n).toBe(0);
    expect(db.prepare("SELECT count(*) n FROM ScoutWishDetails").get().n).toBe(0);
    expect(db.prepare("SELECT status FROM CollectionPlan WHERE title='Scout UI 金签'").get().status).toBe("planned");
  });
  page.once("dialog", dialog => dialog.accept());
  await wish.getByRole("button", { name: "删除", exact: true }).click();
  await expect(wish).toHaveCount(0);
});
